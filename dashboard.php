$stmt = $conn->prepare("SELECT COUNT(*) AS total FROM reservas WHERE data_reserva = ? AND status != 'cancelada'");
if (!$stmt) die('SQL error (reservas hoje): ' . $conn->error);
$stmt->bind_param('s', $hoje);
$stmt->execute();
$reservasHoje = $stmt->get_result()->fetch_assoc()['total'];
$stmt->close();

// KPI: active rooms
$r = $conn->query("SELECT COUNT(*) AS total FROM salas WHERE status = 'ativa'");
if (!$r) die('SQL error (salas ativas): ' . $conn->error);
$salasAtivas = $r->fetch_assoc()['total'];

