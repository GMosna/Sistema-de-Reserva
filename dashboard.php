// KPI: pending reservations
$stmt = $conn->prepare("SELECT COUNT(*) AS total FROM reservas WHERE status = 'pendente' AND data_reserva >= ?");
if (!$stmt) die('SQL error (pendentes): ' . $conn->error);
$stmt->bind_param('s', $hoje);
$stmt->execute();
$pendentes = $stmt->get_result()->fetch_assoc()['total'];
$stmt->close();

// Normal reservations (not generated by recurrence), today and future, max 10
$stmt = $conn->prepare("
    SELECT r.data_reserva, r.hora_inicio, r.hora_fim, r.assunto, r.status,
           s.nome AS sala_nome, u.nome AS usuario_nome
    FROM reservas r
    JOIN salas s ON s.id = r.sala_id
    JOIN usuarios u ON u.id = r.usuario_id
    WHERE r.data_reserva >= ? AND r.status != 'cancelada' AND r.recorrencia_id IS NULL
    ORDER BY r.data_reserva ASC, r.hora_inicio ASC
    LIMIT 10
");
if (!$stmt) die('SQL error (normais): ' . $conn->error);
$stmt->bind_param('s', $hoje);
$stmt->execute();
$normais = $stmt->get_result();
$stmt->close();

