    FROM reservas r
    JOIN salas s ON s.id = r.sala_id
    JOIN usuarios u ON u.id = r.usuario_id
    WHERE r.data_reserva >= ? AND r.data_reserva <= ?
    ORDER BY r.hora_inicio ASC
");
