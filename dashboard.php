<script>
var calEvents = ' . json_encode($calAllJson, JSON_HEX_TAG | JSON_HEX_APOS) . ';
var _calModal = null;

function calShowDay(dateStr) {
    var evts = calEvents.filter(function(e) { return e.date === dateStr; });
    var parts = dateStr.split("-");
    var dayNames = ["Domingo","Segunda-feira","Terça-feira","Quarta-feira","Quinta-feira","Sexta-feira","Sábado"];
    var dt = new Date(parseInt(parts[0]), parseInt(parts[1])-1, parseInt(parts[2]));
    var title = dayNames[dt.getDay()] + ", " + parts[2] + "/" + parts[1] + "/" + parts[0];
    document.getElementById("calDayModalTitle").textContent = title;

    var html = "";
    if (evts.length === 0) {
        html = "<p style=\"color:#858896;text-align:center;padding:1rem 0\">Sem reservas neste dia.</p>";
    } else {
        html = "<div style=\"display:flex;flex-direction:column;gap:4px\">";
        evts.forEach(function(ev) {
            var cls = "st-" + ev.status;
            html += "<div class=\"cal-evt " + cls + "\">"
                  + "<span class=\"evt-time\">" + ev.inicio + " – " + ev.fim + "</span> "
                  + "<span class=\"evt-title\">" + escHtml(ev.assunto) + "</span>"
                  + " <span class=\"evt-user\">&middot; " + escHtml(ev.sala) + " &middot; " + escHtml(ev.user) + "</span>"
                  + "</div>";
        });
        html += "</div>";
    }
    document.getElementById("calDayModalBody").innerHTML = html;
    if (!_calModal) _calModal = new bootstrap.Modal(document.getElementById("calDayModal"));
    _calModal.show();
}

function escHtml(t) {
    var d = document.createElement("div");
    d.appendChild(document.createTextNode(t));
    return d.innerHTML;
}
